import { test } from 'node:test';
import assert from 'node:assert/strict';
import { excerpt, parseArticle, serializeArticle } from '../src/article.js';

const sample = `---
title: "东京语言学校校外活动｜参观"
description: "摘要"
date: 2026-10-13T07:01:58.000Z
tags: ["校外活动", "校园生活"]
legacy:
  pc: 90
  mobile: 91
---

正文第一段。

![](/uploads/a.webp "说明")
`;

test('parsing and writing back leaves the file byte-for-byte identical, unknown fields included', () => {
  const a = parseArticle('90', sample);
  assert.equal(a.title, '东京语言学校校外活动｜参观');
  assert.deepEqual(a.tags, ['校外活动', '校园生活']);
  assert.deepEqual(a.extra, { legacy: { pc: 90, mobile: 91 } });
  assert.equal(serializeArticle(a), sample);
});

test('the draft flag, and a summary generated from the body', () => {
  const a = parseArticle('1', '---\ntitle: "T"\ndate: 2026-01-01\ntags: []\n---\n\n![](/x.webp)\n\n**很长**的正文\n');
  const out = serializeArticle({ ...a, draft: true, description: '' });
  assert.match(out, /^draft: true$/m);
  assert.match(out, /^description: "很长的正文"$/m);
});

test('quotes and colons in a title do not break the YAML', () => {
  const a = parseArticle('2', serializeArticle({ id: '2', title: '他说："你好: 世界"', description: '', date: '2026-01-01T00:00:00Z', tags: ['a'], draft: false, extra: {}, body: 'x' }));
  assert.equal(a.title, '他说："你好: 世界"');
});

test('a generated summary is not mistaken for a written one: it follows the body when that changes', () => {
  const first = serializeArticle({ id: '3', title: 'T', description: '', date: '2026-01-01T00:00:00Z', tags: [], draft: false, extra: {}, body: '旧的开头。' });
  const a = parseArticle('3', first);
  assert.equal(a.description, '', 'opened again, the summary is still the automatic one');
  assert.match(serializeArticle({ ...a, body: '新的开头。' }), /^description: "新的开头。"$/m);
  // One written by hand is kept, even when the body changes
  const b = parseArticle('3', first.replace('"旧的开头。"', '"手写的摘要"'));
  assert.equal(b.description, '手写的摘要');
});

test('a summary generated by an earlier version is recognised as generated too', () => {
  // Up to 0.9.0 the tags went in, less their closing brackets
  const old = '<aside class="notice"这里很重要</aside';
  const file = `---\ntitle: "T"\ndescription: ${JSON.stringify(old)}\ndate: 2026-01-01T00:00:00.000Z\ntags: []\n---\n\n<aside class="notice">这里很重要</aside>\n`;
  const a = parseArticle('4', file);
  assert.equal(a.description, '');
  assert.match(serializeArticle(a), /^description: "这里很重要"$/m);
});

test('the summary leaves out markup, code and tables, and keeps the words', () => {
  const body = [
    '<aside class="notice">报名截止**周五**</aside>',
    '<YouTube id="abc" />',
    '```js\nconst x = 1;\n```',
    '| a | b |\n| - | - |\n| 1 | 2 |',
    '<table><tr><td>格子</td></tr></table>',
    '## 小标题',
    '> 引用的话，snake_case 和 _强调_ 以及 `code` &amp; [链接](/x)',
  ].join('\n\n');
  assert.equal(excerpt(body), '报名截止周五 小标题 引用的话，snake_case 和 强调 以及 code & 链接');
});

test('the summary does not stop halfway through an English word', () => {
  const s = excerpt('word '.repeat(30), 23);
  assert.equal(s, 'word word word word');
  assert.equal(excerpt('一二三四五六', 4), '一二三四');
});
